# Embeds a Lua source file into a C++ header as a raw string (used by build.cmd).
# usage: embed_lua.ps1 <in.lua> <out.h>   -> static const char k<CamelName>Lua[] = R"MCLUA(...)MCLUA" ...;
param([Parameter(Mandatory)][string]$In, [Parameter(Mandatory)][string]$Out)
$ErrorActionPreference = 'Stop'
$src = [IO.File]::ReadAllText($In)
$name = [IO.Path]::GetFileNameWithoutExtension($In)
$id = 'k' + (($name -split '_' | ForEach-Object { $_.Substring(0, 1).ToUpper() + $_.Substring(1) }) -join '') + 'Lua'
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine("// generated by build.cmd from src/game/$name.lua; do not edit")
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine("static const char $id[] =")
# MSVC limits a single string literal piece to 16 KB; adjacent pieces are concatenated.
for ($i = 0; $i -lt $src.Length; $i += 8000) {
    $chunk = $src.Substring($i, [Math]::Min(8000, $src.Length - $i))
    [void]$sb.AppendLine('R"MCLUA(' + $chunk + ')MCLUA"')
}
[void]$sb.AppendLine(';')
[IO.File]::WriteAllText($Out, $sb.ToString())
