// fontgen: dev-time generator for src/render/font8x16.h (the overlay's built-in bitmap font).
// Renders ASCII 32..126 from an installed Windows font with GDI (grayscale antialiasing) into 8x16 cells and
// writes them as an 8-bit coverage array. Cell 95 (character 127) is filled solid and used for rectangles.
// The output header is checked in; nothing is read from font files at runtime.
//
// Build + run (x64 Native Tools prompt, from the core repo's root):
//   cl /nologo /EHsc /std:c++20 /DUNICODE /D_UNICODE tools\fontgen.cpp /Fe:out\fontgen.exe /Fo:out\obj\ gdi32.lib user32.lib
//   out\fontgen.exe src\render\font8x16.h [face] [pixel height]      (default: Consolas 14)
#include <windows.h>

#include <cstdio>
#include <cstring>
#include <algorithm>
#include <string>
#include <vector>

constexpr int kCellW = 8;
constexpr int kCellH = 16;
constexpr int kFirst = 32;
constexpr int kCount = 96;  // 32..127

int wmain(int argc, wchar_t** argv) {
    if (argc < 2) {
        std::fwprintf(stderr, L"usage: fontgen <out.h> [face] [pixel height]\n");
        return 1;
    }
    const wchar_t* face = argc > 2 ? argv[2] : L"Consolas";
    int height = argc > 3 ? _wtoi(argv[3]) : 14;

    HDC dc = CreateCompatibleDC(nullptr);
    BITMAPINFO bi{};
    bi.bmiHeader.biSize = sizeof(bi.bmiHeader);
    bi.bmiHeader.biWidth = kCellW;
    bi.bmiHeader.biHeight = -kCellH;  // top-down
    bi.bmiHeader.biPlanes = 1;
    bi.bmiHeader.biBitCount = 32;
    bi.bmiHeader.biCompression = BI_RGB;
    void* bits = nullptr;
    HBITMAP bmp = CreateDIBSection(dc, &bi, DIB_RGB_COLORS, &bits, nullptr, 0);
    SelectObject(dc, bmp);
    HFONT font = CreateFontW(-height, 0, 0, 0, FW_NORMAL, FALSE, FALSE, FALSE, ANSI_CHARSET, OUT_TT_PRECIS,
                             CLIP_DEFAULT_PRECIS, ANTIALIASED_QUALITY, FIXED_PITCH | FF_MODERN, face);
    SelectObject(dc, font);
    SetTextColor(dc, RGB(255, 255, 255));
    SetBkColor(dc, RGB(0, 0, 0));
    SetBkMode(dc, OPAQUE);
    TEXTMETRICW tm{};
    GetTextMetricsW(dc, &tm);
    const int yOff = (kCellH - tm.tmHeight) / 2;

    std::vector<unsigned char> out(kCount * kCellW * kCellH);
    for (int i = 0; i < kCount; ++i) {
        unsigned char* cell = &out[i * kCellW * kCellH];
        if (i == kCount - 1) {
            std::fill(cell, cell + kCellW * kCellH, static_cast<unsigned char>(255));
            continue;
        }
        std::memset(bits, 0, kCellW * kCellH * 4);
        wchar_t ch = static_cast<wchar_t>(kFirst + i);
        SIZE sz{};
        GetTextExtentPoint32W(dc, &ch, 1, &sz);
        RECT rc{0, 0, kCellW, kCellH};
        ExtTextOutW(dc, (kCellW - sz.cx) / 2, yOff, ETO_OPAQUE | ETO_CLIPPED, &rc, &ch, 1, nullptr);
        GdiFlush();
        const auto* px = static_cast<const unsigned char*>(bits);
        for (int p = 0; p < kCellW * kCellH; ++p) cell[p] = px[p * 4 + 1];  // green channel = coverage
    }

    FILE* f = nullptr;
    _wfopen_s(&f, argv[1], L"wb");
    if (!f) {
        std::fwprintf(stderr, L"cannot write %s\n", argv[1]);
        return 1;
    }
    std::fprintf(f, "// Generated by tools/fontgen.cpp from \"%ls\" %dpx (GDI, grayscale AA). Do not edit by hand.\n",
                 face, height);
    std::fprintf(f, "// %d cells of %dx%d 8-bit coverage, characters %d..%d; the last cell is solid (rectangles).\n",
                 kCount, kCellW, kCellH, kFirst, kFirst + kCount - 1);
    std::fprintf(f, "#pragma once\n\nnamespace mc::render::font {\n\n");
    std::fprintf(f, "constexpr int kCellW = %d;\nconstexpr int kCellH = %d;\nconstexpr int kFirst = %d;\n"
                    "constexpr int kCount = %d;\nconstexpr int kSolid = %d;  // cell index of the solid block\n\n",
                 kCellW, kCellH, kFirst, kCount, kCount - 1);
    std::fprintf(f, "inline constexpr unsigned char kPixels[%zu] = {\n", out.size());
    for (size_t i = 0; i < out.size(); ++i) {
        if (i % 32 == 0) std::fprintf(f, "    ");
        std::fprintf(f, "%u,", out[i]);
        if (i % 32 == 31) std::fprintf(f, "\n");
    }
    std::fprintf(f, "};\n\n}  // namespace mc::render::font\n");
    std::fclose(f);
    std::printf("wrote %ls (%s %dpx, tmHeight %ld, avg width %ld)\n", argv[1], "font", height, tm.tmHeight,
                tm.tmAveCharWidth);
    DeleteObject(font);
    DeleteObject(bmp);
    DeleteDC(dc);
    return 0;
}
